# Token limits per request (input + output)
MAX_INPUT_TOKENS = 2000
MAX_OUTPUT_TOKENS = 2000
MAX_REQUEST_LENGTH = 500  # Max characters in user request

# Rate limiting (per site per hour)
RATE_LIMIT_PER_HOUR = 20
rate_limit_cache: Dict[str, List[datetime]] = {}

def check_rate_limit(site_id: str) -> Tuple[bool, str]:
    """Check if rate limit exceeded for site"""
    now = datetime.now(timezone.utc)
    hour_ago = now.replace(microsecond=0, second=0, minute=now.minute)
    
    if site_id not in rate_limit_cache:
        rate_limit_cache[site_id] = []
    
    # Clean old entries
    rate_limit_cache[site_id] = [
        t for t in rate_limit_cache[site_id] 
        if (now - t).total_seconds() < 3600
    ]
    
    if len(rate_limit_cache[site_id]) >= RATE_LIMIT_PER_HOUR:
        return False, f"Rate limit superato: max {RATE_LIMIT_PER_HOUR} richieste/ora. Riprova tra qualche minuto."
    
    return True, ""

def record_request(site_id: str):
    """Record a request for rate limiting"""
    if site_id not in rate_limit_cache:
        rate_limit_cache[site_id] = []
    rate_limit_cache[site_id].append(datetime.now(timezone.utc))

