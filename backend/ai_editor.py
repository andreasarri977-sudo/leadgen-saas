def generate_preview_diff(original: SiteContent, modified: SiteContent) -> List[Dict[str, Any]]:
    """
    Generate a human-readable diff between original and modified content.
    """
    diffs = []
    
    # Compare business info
    if original.business.model_dump() != modified.business.model_dump():
        for field in ['name', 'phone', 'whatsapp', 'email', 'address']:
            orig_val = getattr(original.business, field)
            mod_val = getattr(modified.business, field)
            if orig_val != mod_val:
                diffs.append({
                    "section": "Contatti",
                    "field": field,
                    "old": orig_val,
                    "new": mod_val
                })
    
    # Compare opening hours
    for day in ['mon', 'tue', 'wed', 'thu', 'fri', 'sat', 'sun']:
        orig_hours = getattr(original.opening_hours, day)
        mod_hours = getattr(modified.opening_hours, day)
        if orig_hours.model_dump() != mod_hours.model_dump():
            day_names = {'mon': 'Lunedì', 'tue': 'Martedì', 'wed': 'Mercoledì', 
                        'thu': 'Giovedì', 'fri': 'Venerdì', 'sat': 'Sabato', 'sun': 'Domenica'}
            diffs.append({
                "section": "Orari",
                "field": day_names[day],
                "old": f"{'Chiuso' if orig_hours.closed else f'{orig_hours.open}-{orig_hours.close}'}",
                "new": f"{'Chiuso' if mod_hours.closed else f'{mod_hours.open}-{mod_hours.close}'}"
            })
    
    # Compare about text
    if original.about_text.local != modified.about_text.local:
        diffs.append({
            "section": "Chi siamo",
            "field": "Testo locale",
            "old": original.about_text.local[:100] + "..." if len(original.about_text.local) > 100 else original.about_text.local,
            "new": modified.about_text.local[:100] + "..." if len(modified.about_text.local) > 100 else modified.about_text.local
        })
    if original.about_text.en != modified.about_text.en:
        diffs.append({
            "section": "Chi siamo",
            "field": "Testo EN",
            "old": original.about_text.en[:100] + "..." if len(original.about_text.en) > 100 else original.about_text.en,
            "new": modified.about_text.en[:100] + "..." if len(modified.about_text.en) > 100 else modified.about_text.en
        })
    
    # Compare hero
    if original.hero.tagline_local != modified.hero.tagline_local:
        diffs.append({
            "section": "Hero",
            "field": "Tagline locale",
            "old": original.hero.tagline_local,
            "new": modified.hero.tagline_local
        })
    
    # Compare menu/services count
    orig_items = sum(len(c.items) for c in original.menu_or_services.categories)
    mod_items = sum(len(c.items) for c in modified.menu_or_services.categories)
    if orig_items != mod_items:
        diffs.append({
            "section": "Menu/Servizi",
            "field": "Totale items",
            "old": str(orig_items),
            "new": str(mod_items)
        })
    
    # Compare gallery
    if len(original.gallery) != len(modified.gallery):
        diffs.append({
            "section": "Galleria",
            "field": "Numero immagini",
            "old": str(len(original.gallery)),
            "new": str(len(modified.gallery))
        })
    
    # Compare SEO
    if original.seo and modified.seo:
        if original.seo.title_local != modified.seo.title_local:
            diffs.append({
                "section": "SEO",
                "field": "Title locale",
                "old": original.seo.title_local,
                "new": modified.seo.title_local
            })
    elif not original.seo and modified.seo:
        diffs.append({
            "section": "SEO",
            "field": "SEO",
            "old": "Non configurato",
            "new": "Configurato"
        })
    
    return diffs
