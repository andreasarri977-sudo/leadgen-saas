class AIProposal(BaseModel):
    """Proposal generated by AI Editor"""
    success: bool
    request: str
    changes_summary: List[str] = Field(default_factory=list)
    patch: Dict[str, Any] = Field(default_factory=dict)
    validation_errors: List[str] = Field(default_factory=list)
    preview_content: Optional[Dict[str, Any]] = None
    error: Optional[str] = None

def get_system_prompt(content: SiteContent) -> str:
    """Generate system prompt for AI Editor"""
    return f"""Sei un assistente per la modifica di contenuti di siti web aziendali.

REGOLE FONDAMENTALI:
1. Puoi modificare SOLO questi campi:
   - business: name, category, address, phone, whatsapp, email
   - opening_hours: orari per ogni giorno (mon-sun)
   - menu_or_services: categorie e items
   - gallery: immagini (solo URL esterni)
   - about_text: testo chi siamo (local + en)
   - hero: tagline (local + en)
   - seo: title e meta (local + en)

2. NON puoi modificare:
   - Layout, design, colori, componenti
   - Codice, routing, script
   - Paese, città, URL Google Maps
   - ID e metadati interni

3. MULTILINGUA OBBLIGATORIO:
   - Lingua locale: {content.locale_lang}
   - Ogni testo deve avere versione locale + inglese
   - Mai mix di lingue nella stessa stringa

4. FORMATO OUTPUT:
   Rispondi SEMPRE in questo formato JSON:
   {{
     "changes_summary": ["Modifica 1 in italiano", "Modifica 2 in italiano"],
     "patch": {{
       "campo.sottocampo": "nuovo valore",
       ...
     }}
   }}

DATI ATTUALI DEL SITO:
- Nome: {content.business.name}
- Categoria: {content.business.category}  
- Città: {content.business.city}
- Lingua locale: {content.locale_lang}
"""

async def generate_ai_proposal(
    content: SiteContent,
    user_request: str,
    preset_type: Optional[str] = None,
    emergent_key: str = ""
) -> AIProposal:
    """
    Generate a modification proposal using AI.
    Returns structured patch + human-readable summary.
    """
    
    # Validate request length
    if len(user_request) > MAX_REQUEST_LENGTH:
        return AIProposal(
            success=False,
            request=user_request[:100] + "...",
            error=f"Richiesta troppo lunga: max {MAX_REQUEST_LENGTH} caratteri"
        )
    
    # Check rate limit
    allowed, error_msg = check_rate_limit(content.demo_id)
    if not allowed:
        return AIProposal(
            success=False,
            request=user_request,
            error=error_msg
        )
    
    # Build prompt
    if preset_type and preset_type in PRESET_PROMPTS:
        preset = PRESET_PROMPTS[preset_type]
        prompt = preset["prompt_template"].format(
            user_input=user_request,
            locale_lang=content.locale_lang,
            category=content.business.category,
            business_name=content.business.name,
            city=content.business.city
        )
    else:
        prompt = f"""Richiesta dell'utente: {user_request}

Analizza la richiesta e genera le modifiche appropriate.
Se la richiesta riguarda testi, genera sempre versione locale ({content.locale_lang}) e inglese."""
    
    # Current content summary for context
    current_summary = f"""
Contenuto attuale:
- Orari: {[f"{d}: {'Chiuso' if getattr(content.opening_hours, d).closed else f'{getattr(content.opening_hours, d).open}-{getattr(content.opening_hours, d).close}'}" for d in ['mon','tue','wed','thu','fri','sat','sun']]}
- Menu/Servizi: {len(content.menu_or_services.categories)} categorie
- Galleria: {len(content.gallery)} immagini
- Chi siamo: {content.about_text.local[:100] if content.about_text.local else 'Non impostato'}...
- Contatti: tel={content.business.phone}, wa={content.business.whatsapp}, email={content.business.email}
"""
    
    full_prompt = prompt + "\n" + current_summary
    
    try:
        chat = LlmChat(
            api_key=emergent_key,
            session_id=f"ai_editor_{content.demo_id}_{datetime.now().timestamp()}",
            system_message=get_system_prompt(content)
        ).with_model("openai", "gpt-5.2")
        
        message = UserMessage(text=full_prompt)
        response = await chat.send_message(message)
        
        # Record request for rate limiting
        record_request(content.demo_id)
        
        # Parse response
        clean_response = response.strip()
        if clean_response.startswith("```"):
            clean_response = re.sub(r'^```(?:json)?\s*', '', clean_response)
            clean_response = re.sub(r'\s*```$', '', clean_response)
        
        try:
            result = json.loads(clean_response)
        except json.JSONDecodeError as e:
            logger.error(f"AI response parse error: {e}\nResponse: {clean_response[:500]}")
            return AIProposal(
                success=False,
                request=user_request,
                error="Errore nel parsing della risposta AI. Riprova con una richiesta più specifica."
            )
        
        changes_summary = result.get("changes_summary", [])
        patch = result.get("patch", {})
        
        # Validate patch
        validation_errors = validate_patch_allowed(patch)
        
        # Check for suspicious content
        patch_str = json.dumps(patch).lower()
        suspicious_patterns = [
            r'<script', r'javascript:', r'onclick', r'onerror',
            r'data:text/html', r'document\.', r'window\.'
        ]
        for pattern in suspicious_patterns:
            if re.search(pattern, patch_str, re.I):
                validation_errors.append(f"Contenuto sospetto rilevato: {pattern}")
        
        return AIProposal(
            success=len(validation_errors) == 0,
            request=user_request,
            changes_summary=changes_summary,
            patch=patch,
            validation_errors=validation_errors
        )
        
    except Exception as e:
        logger.error(f"AI proposal generation error: {str(e)}")
        return AIProposal(
            success=False,
            request=user_request,
            error=f"Errore generazione proposta: {str(e)}"
        )

# ============================================
# APPLY PATCH TO CONTENT
# ============================================

def apply_patch_to_content(content: SiteContent, patch: Dict[str, Any]) -> Tuple[SiteContent, List[str]]:
    """
    Apply a patch to SiteContent.
    Returns (updated_content, errors).
    """
    errors = []
    
    # First validate patch
    patch_errors = validate_patch_allowed(patch)
    if patch_errors:
        return content, patch_errors
    
    # Convert to dict for easier manipulation
    content_dict = content.model_dump()
    
    def set_nested(d: dict, path: str, value: Any):
        """Set a nested value using dot notation"""
        keys = path.split('.')
        for key in keys[:-1]:
            if key.isdigit():
                key = int(key)
            if isinstance(d, list):
                d = d[key]
            else:
                d = d.setdefault(key, {})
        final_key = keys[-1]
        if final_key.isdigit():
            final_key = int(final_key)
        if isinstance(d, list):
            if final_key >= len(d):
                d.append(value)
            else:
                d[final_key] = value
        else:
            d[final_key] = value
    
    # Apply each patch entry
    for path, value in patch.items():
        try:
            # Handle special cases
            if path == "opening_hours" and isinstance(value, dict):
                # Merge hours instead of replace
                for day, hours in value.items():
                    if day in ['mon', 'tue', 'wed', 'thu', 'fri', 'sat', 'sun']:
                        content_dict['opening_hours'][day].update(hours)
            elif path == "menu_or_services" and isinstance(value, dict):
                # Handle menu/services specially
                if 'mode' in value:
                    content_dict['menu_or_services']['mode'] = value['mode']
                if 'categories' in value:
                    content_dict['menu_or_services']['categories'] = value['categories']
            elif path == "gallery" and isinstance(value, list):
                # Replace gallery
                content_dict['gallery'] = value
            elif path.startswith("gallery.") and path[8:].isdigit():
                # Update single gallery item
                idx = int(path[8:])
                if idx < len(content_dict['gallery']):
                    content_dict['gallery'][idx].update(value)
            else:
                set_nested(content_dict, path, value)
        except Exception as e:
            errors.append(f"Errore applicazione patch '{path}': {str(e)}")
    
    if errors:
        return content, errors
    
    # Update metadata
    content_dict['last_updated'] = datetime.now(timezone.utc).isoformat()
    
    try:
        updated_content = SiteContent.model_validate(content_dict)
        
        # Validate final content
        content_errors = validate_content(updated_content)
        if content_errors:
            return content, content_errors
        
        return updated_content, []
    except Exception as e:
        return content, [f"Errore validazione contenuto: {str(e)}"]

def create_change_log_entry(request: str, changes_summary: List[str], patch: Dict[str, Any]) -> ChangeLogEntry:
    """Create a changelog entry for the modification"""
    return ChangeLogEntry(
        timestamp=datetime.now(timezone.utc),
        request=request,
        changes_summary=changes_summary,
        patch=patch,
        applied_by="ai_editor"
    )

